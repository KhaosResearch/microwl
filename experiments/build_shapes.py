"""Generate the SHACL shape files of MicrOWL (experiments/shapes/).

* microwl-shapes.ttl         counterpart of the SWRL rules with the same (open-world) semantics,
                             including the open-world S2
* microwl-shapes-closed.ttl  closed-world variant of every constraint (S2c instead of S2)
* microwl-shapes-hybrid-asserted.ttl  the same constraints as microwl-shapes-hybrid.ttl, resolving
                             names in SPARQL over the asserted ABox (ablation in scalability.py)
* microwl-shapes-hybrid.ttl  closed-world shapes evaluated by the hybrid validator after the
                             SWRL rules, over the reasoned graph: S9, S10 and S13 use the
                             resolvesTo relations inferred by rule D1 instead of resolving names
                             again (the constraints that need negation as failure)

Every message starts with the identifier of the constraint (S3 covers S3a, S3b and S4; S8 covers
S8a and S8b), which the experiments use for rule attribution, and reports the values involved
({?var} is replaced by the value of a variable of the query). Warnings (S5, S11, S16) are grouped
in shapes with sh:severity sh:Warning; the other constraints are violations. The closed-world
constraints that resolve names within a deployment unit (S10, S12, S13) are not evaluated on units
marked as incomplete.

Usage: python build_shapes.py
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent / "shapes"
HEAD = '''@prefix sh:    <http://www.w3.org/ns/shacl#> .
@prefix xsd:   <http://www.w3.org/2001/XMLSchema#> .
@prefix mw:    <http://www.khaos.uma.es/microwl/> .
@prefix omsac: <http://www.semanticweb.org/ontologyOfMicroservicesArchitecture/> .
@prefix ex:    <http://www.khaos.uma.es/microwl/shapes/> .
@prefix owl:   <http://www.w3.org/2002/07/owl#> .

ex: a owl:Ontology ;
  sh:declare [ sh:prefix "mw" ; sh:namespace "http://www.khaos.uma.es/microwl/"^^xsd:anyURI ] .

# %s
# Generated by experiments/build_shapes.py. Every message starts with the identifier of the
# constraint (S3 covers S3a, S3b and S4, S8 covers S8a and S8b). Warnings have sh:severity sh:Warning.
'''
R1 = '$this mw:hasWorkloadSpec/mw:hasReplicas ?r . FILTER(?r > 1)'
COMPLETE = 'FILTER NOT EXISTS { ?u mw:isIncomplete true }'
DEP = '''$this mw:hasDependency ?d ; mw:inDeployment ?u . ?d mw:dependsOnHost ?h .
      ?e a mw:ServiceEndpoint ; mw:inDeployment ?u ; mw:hasEndpointName ?n . FILTER(str(?n) = str(?h))'''
PORT = '''?d mw:dependsOnPort ?p .
      FILTER EXISTS { ?e mw:hasEndpointPort ?any }
      FILTER NOT EXISTS { ?e mw:hasEndpointPort ?q . FILTER(?q = ?p) }'''
PORTNAME = '''?d mw:dependsOnPortName ?pn .
      FILTER NOT EXISTS { ?e mw:hasEndpointPortName ?qn . FILTER(str(?qn) = str(?pn)) }'''
# over the reasoned graph (hybrid validator): the endpoint of a dependency is the one inferred by D1
DEP_R = '''$this mw:hasDependency ?d . ?d mw:dependsOnHost ?h ; mw:resolvesTo ?e .'''
UNRESOLVED_R = f'''$this mw:hasDependency ?d ; mw:inDeployment ?u . ?d mw:dependsOnHost ?h .
      {COMPLETE}
      FILTER NOT EXISTS {{ ?d mw:resolvesTo ?e }}'''
UNRESOLVED = f'''$this mw:hasDependency ?d ; mw:inDeployment ?u . ?d mw:dependsOnHost ?h .
      {COMPLETE}
      FILTER NOT EXISTS {{ ?e a mw:ServiceEndpoint ; mw:inDeployment ?u ; mw:hasEndpointName ?n .
                          FILTER(str(?n) = str(?h)) }}'''

# (constraint, target, severity, message, query body)
C = [
    ("S1", "ms", "V", "{?r} replicas share a ReadWriteOnce volume", f'''{R1}
      $this mw:hasStorageSpec ?st . ?st a mw:SharedStorageSpecification ;
        mw:hasAccessMode ?am . FILTER(str(?am) = "ReadWriteOnce")'''),
    ("S2", "ms", "V", "target port {?t} differs from container port {?c}", '''$this mw:hasContainerSpec/mw:hasContainerPort ?c ;
            mw:hasNetworkSpec/mw:hasTargetPort ?t . FILTER(?c != ?t)'''),
    ("S2c", "ms", "V", "target port {?t} matches none of the container ports", '''$this mw:hasNetworkSpec/mw:hasTargetPort ?t .
      FILTER EXISTS { $this mw:hasContainerSpec/mw:hasContainerPort ?any }
      FILTER NOT EXISTS { $this mw:hasContainerSpec/mw:hasContainerPort ?t2 . FILTER(?t2 = ?t) }'''),
    ("S3", "ms", "V", "NodePort {?p} outside [30000, 32767]", '''$this mw:hasPlatformConfig ?k . ?k a mw:KubernetesConfig ;
        mw:hasResource ?res . ?res a mw:NodePortResource ; mw:hasNodePortValue ?p .
      FILTER(?p < 30000 || ?p > 32767)'''),
    ("S5", "ms", "W", "ReadWriteOnce storage with {?r} replicas", '''$this mw:hasWorkloadSpec/mw:hasReplicas ?r . FILTER(?r < 1)
      $this mw:hasStorageSpec/mw:hasAccessMode ?am . FILTER(str(?am) = "ReadWriteOnce")'''),
    ("S7", "ms", "V", "{?r} replicas bind host port {?h}", f'''{R1}
      $this mw:hasNetworkSpec/mw:hasHostPort ?h .'''),
    ("S8", "ms", "V", "host port {?h} is also published by another service of the Compose file", '''$this mw:inDeployment ?u ; mw:hasPlatformConfig ?c1 ; mw:hasNetworkSpec/mw:hasHostPort ?h .
      ?c1 a mw:DockerComposeConfig .
      ?m2 mw:inDeployment ?u ; mw:hasPlatformConfig ?c2 ; mw:hasNetworkSpec/mw:hasHostPort ?h2 .
      ?c2 a mw:DockerComposeConfig . FILTER(?h2 = ?h && ?m2 != $this)'''),
    ("S8", "ep", "V", "NodePort {?p} is also opened by another endpoint of the deployment unit", '''$this mw:inDeployment ?u ; mw:hasEndpointNodePort ?p .
      ?e2 a mw:ServiceEndpoint ; mw:inDeployment ?u ; mw:hasEndpointNodePort ?p2 .
      FILTER(?p2 = ?p && ?e2 != $this)'''),
    ("S9", "ms", "V", "dependency on {?h} uses port {?p}, which the endpoint does not serve", f"{DEP}\n      {PORT}"),
    ("S9", "ms", "V", "dependency on {?h} uses port name {?pn}, which the endpoint does not define", f"{DEP}\n      {PORTNAME}"),
    ("S10", "ms", "V", "dependency on {?h} names no endpoint of the deployment unit", UNRESOLVED),
    ("S11", "ms", "W", "{?r} replicas started from the mutable tag {?t}", f'''{R1}
      $this mw:hasContainerSpec/mw:hasImageTag ?t . FILTER(str(?t) = "latest")'''),
    ("S12", "ep", "V", "the endpoint selects no microservice", '''$this mw:hasSelector ?s . FILTER(?s = true)
      FILTER NOT EXISTS { $this mw:inDeployment/mw:isIncomplete true }
      FILTER NOT EXISTS { $this mw:routesTo ?m }'''),
    ("S13", "ing", "V", "Ingress backend {?h} names no endpoint of the deployment unit", UNRESOLVED),
    ("S13", "ing", "V", "Ingress backend {?h} uses port {?p}, which the endpoint does not serve", f"{DEP}\n      {PORT}"),
    ("S13", "ing", "V", "Ingress backend {?h} uses port name {?pn}, which the endpoint does not define", f"{DEP}\n      {PORTNAME}"),
    ("S14", "ms", "V", "probe port {?pp} is not a container port", '''$this mw:hasContainerSpec ?ct . ?ct mw:hasProbePort ?pp .
      FILTER EXISTS { ?ct mw:hasContainerPort ?any }
      FILTER NOT EXISTS { ?ct mw:hasContainerPort ?c . FILTER(?c = ?pp) }'''),
    ("S15", "ms", "V", "{?r} replicas share a ReadWriteOncePod volume", f'''{R1}
      $this mw:hasStorageSpec ?st . ?st a mw:SharedStorageSpecification ;
        mw:hasAccessMode ?am . FILTER(str(?am) = "ReadWriteOncePod")'''),
    ("S16", "ms", "W", "no memory limit declared", '''FILTER NOT EXISTS { $this mw:hasContainerSpec/mw:hasMemoryLimit ?l }'''),
]
# hybrid validator: S9, S10 and S13 over the resolvesTo relations inferred by D1
HYBRID_OVERRIDE = [
    ("S9", "ms", "V", "dependency on {?h} uses port {?p}, which the endpoint does not serve", f"{DEP_R}\n      {PORT}"),
    ("S9", "ms", "V", "dependency on {?h} uses port name {?pn}, which the endpoint does not define", f"{DEP_R}\n      {PORTNAME}"),
    ("S10", "ms", "V", "dependency on {?h} names no endpoint of the deployment unit", UNRESOLVED_R),
    ("S13", "ing", "V", "Ingress backend {?h} names no endpoint of the deployment unit", UNRESOLVED_R),
    ("S13", "ing", "V", "Ingress backend {?h} uses port {?p}, which the endpoint does not serve", f"{DEP_R}\n      {PORT}"),
    ("S13", "ing", "V", "Ingress backend {?h} uses port name {?pn}, which the endpoint does not define", f"{DEP_R}\n      {PORTNAME}"),
]
TARGETS = {"ms": ("Microservice", "omsac:Microservice"), "ep": ("Endpoint", "mw:ServiceEndpoint"),
           "ing": ("Ingress", "mw:KubernetesIngress")}


def write(name, comment, keys, constraints=None):
    out = HEAD % comment
    constraints = constraints or C
    for tkey, (tname, tcls) in TARGETS.items():
        for sev, sname, iri in (("V", "", "sh:Violation"), ("W", "Warning", "sh:Warning")):
            items = [c for c in constraints if c[0] in keys and c[1] == tkey and c[2] == sev]
            if not items:
                continue
            parts = [f'''  sh:sparql [ sh:prefixes ex: ; sh:message "{cid}: {msg}" ;
    sh:select """SELECT {" ".join(["$this"] + ["?" + v for v in dict.fromkeys(re.findall(r"[{][?](\w+)[}]", msg))])} WHERE {{
      {body} }}""" ]''' for cid, _, _, msg, body in items]
            out += (f"\nex:{tname}{sname}Shape a sh:NodeShape ;\n  sh:targetClass {tcls} ;\n"
                    f"  sh:severity {iri} ;\n" + " ;\n".join(parts) + " .\n")
    (HERE / name).write_text(out)


if __name__ == "__main__":
    write("microwl-shapes.ttl", "SHACL counterpart of the SWRL rules of MicrOWL with the same (open-world) semantics,\n"
          "# including the open-world S2.", {"S1", "S2", "S3", "S5", "S7", "S8", "S11", "S15"})
    write("microwl-shapes-closed.ttl", "Closed-world variant of every MicrOWL constraint (S2c instead of S2, plus the\n"
          "# constraints that need negation as failure: S9, S10, S12, S13, S14, S16).",
          {"S1", "S2c", "S3", "S5", "S7", "S8", "S9", "S10", "S11", "S12", "S13", "S14", "S15", "S16"})
    write("microwl-shapes-hybrid-asserted.ttl", "Ablation of the hybrid validator: the closed-world shapes of the hybrid validator\n"
          "# resolving dependency names in SPARQL over the asserted ABox (used in scalability.py).",
          {"S2c", "S9", "S10", "S12", "S13", "S14", "S16"})
    hybrid = [c for c in C if c[0] not in ("S9", "S10", "S13")] + HYBRID_OVERRIDE
    write("microwl-shapes-hybrid.ttl", "Closed-world shapes evaluated by the MicrOWL hybrid validator after the SWRL rules, over\n"
          "# the reasoned graph (the constraints that need negation as failure). S9, S10 and S13 use the\n"
          "# resolvesTo relations inferred by rule D1.", {"S2c", "S9", "S10", "S12", "S13", "S14", "S16"}, hybrid)
