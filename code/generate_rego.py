#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Generates the Rego policy equivalent to the six MicrOWL SWRL rules and
reports authoring-effort metrics (lines of code).

Usage:
    python generate_rego.py --output rego_policies/microwl.rego
"""

import argparse
from pathlib import Path


# SWRL rules as they appear in the MicrOWL ontology.
# Each entry is a tuple (rule_id, description, swrl_body_lines).
SWRL_RULES = [
    (
        "S1",
        "replicas > 1 AND accessMode=ReadWriteOnce -> InconsistentDeployment",
        [
            "WorkloadSpecification(?w) ∧ hasReplicas(?w, ?r) ∧",
            "swrlb:greaterThan(?r, 1) ∧ workloadSpecOf(?w, ?ms) ∧",
            "hasStorageSpec(?ms, ?s) ∧ hasAccessMode(?s, \"ReadWriteOnce\")",
            "-> InconsistentDeployment(?ms)",
        ],
    ),
    (
        "S2",
        "containerPort != exposedPort -> InconsistentDeployment",
        [
            "Microservice(?ms) ∧ hasContainerSpec(?ms, ?c) ∧",
            "hasContainerPort(?c, ?cport) ∧ hasNetworkSpec(?ms, ?n) ∧",
            "hasExposedPort(?n, ?eport) ∧ swrlb:notEqual(?cport, ?eport)",
            "-> InconsistentDeployment(?ms)",
        ],
    ),
    (
        "S3a",
        "kubernetes.nodePort < 30000 -> NodePortOutOfRange",
        [
            "KubernetesConfig(?k) ∧ hasResource(?k, ?r) ∧",
            "resourceType(?r, \"nodePort\") ∧ resourceValue(?r, ?p) ∧",
            "swrlb:lessThan(?p, 30000) -> NodePortOutOfRange(?k)",
        ],
    ),
    (
        "S3b",
        "kubernetes.nodePort > 32767 -> NodePortOutOfRange",
        [
            "KubernetesConfig(?k) ∧ hasResource(?k, ?r) ∧",
            "resourceType(?r, \"nodePort\") ∧ resourceValue(?r, ?p) ∧",
            "swrlb:greaterThan(?p, 32767) -> NodePortOutOfRange(?k)",
        ],
    ),
    (
        "S4",
        "NodePortOutOfRange(k) AND platformConfigOf(k, ms) -> InconsistentDeployment(ms)",
        [
            "NodePortOutOfRange(?k) ∧ platformConfigOf(?k, ?ms) ∧",
            "Microservice(?ms) -> InconsistentDeployment(?ms)",
        ],
    ),
    (
        "S5",
        "replicas < 1 AND accessMode=ReadWriteOnce -> InconsistentDeployment",
        [
            "Microservice(?ms) ∧ hasStorageSpec(?ms, ?s) ∧",
            "hasAccessMode(?s, \"ReadWriteOnce\") ∧",
            "hasWorkloadSpec(?ms, ?w) ∧ hasReplicas(?w, ?r) ∧",
            "swrlb:lessThan(?r, 1) -> InconsistentDeployment(?ms)",
        ],
    ),
]


# Rego policy (verbatim template).
REGO_POLICY = """\
# =============================================================================
# MicrOWL policies in Rego
# -----------------------------------------------------------------------------
# Auto-generated by generate_rego.py. Do not edit manually.
# Implements the six cross-resource constraints of the MicrOWL ontology,
# corresponding to SWRL rules S1, S2, S3a, S3b, S4, S5.
# =============================================================================

package microwl

# -----------------------------------------------------------------------------
# Rule S1: replica vs. storage access mode consistency
# -----------------------------------------------------------------------------
inconsistent if {{
    input.replicas > 1
    input.accessMode == "ReadWriteOnce"
}}

# -----------------------------------------------------------------------------
# Rule S2: container port vs. exposed port alignment
# -----------------------------------------------------------------------------
inconsistent if {{
    input.containerPort != input.exposedPort
}}

# -----------------------------------------------------------------------------
# Rule S3a: NodePort lower bound
# -----------------------------------------------------------------------------
node_port_out_of_range if {{
    input.kubernetes
    input.kubernetes.nodePort
    input.kubernetes.nodePort < 30000
}}

# -----------------------------------------------------------------------------
# Rule S3b: NodePort upper bound
# -----------------------------------------------------------------------------
node_port_out_of_range if {{
    input.kubernetes
    input.kubernetes.nodePort
    input.kubernetes.nodePort > 32767
}}

# -----------------------------------------------------------------------------
# Rule S4: propagate NodePortOutOfRange to the microservice
# -----------------------------------------------------------------------------
inconsistent if {{
    node_port_out_of_range
}}

# -----------------------------------------------------------------------------
# Rule S5: minimum replica for stateful services
# -----------------------------------------------------------------------------
inconsistent if {{
    input.replicas < 1
    input.accessMode == "ReadWriteOnce"
}}

# -----------------------------------------------------------------------------
# Decision exposed to the caller
# -----------------------------------------------------------------------------
deny := true if inconsistent

# -----------------------------------------------------------------------------
# Reasons (explanation parity with Pellet)
# -----------------------------------------------------------------------------
reasons contains "S1_replica_access_mode" if {{
    input.replicas > 1
    input.accessMode == "ReadWriteOnce"
}}

reasons contains "S2_port_alignment" if {{
    input.containerPort != input.exposedPort
}}

reasons contains "S3a_nodeport_lower_bound" if {{
    input.kubernetes
    input.kubernetes.nodePort
    input.kubernetes.nodePort < 30000
}}

reasons contains "S3b_nodeport_upper_bound" if {{
    input.kubernetes
    input.kubernetes.nodePort
    input.kubernetes.nodePort > 32767
}}

reasons contains "S5_minimum_replica_stateful" if {{
    input.replicas < 1
    input.accessMode == "ReadWriteOnce"
}}
"""


# =============================================================================
# LOC METRICS
# =============================================================================

def count_code_lines(text, strip_comments=False):
    """Count non-empty, non-comment lines."""
    n = 0
    for line in text.splitlines():
        s = line.strip()
        if not s:
            continue
        if strip_comments and s.startswith("#"):
            continue
        n += 1
    return n


def compute_swrl_loc():
    """Count effective lines of SWRL code."""
    total = 0
    for _, _, body in SWRL_RULES:
        total += len(body)
    return total


def compute_rego_loc():
    """Count effective lines of Rego code (excluding comments and blanks)."""
    return count_code_lines(REGO_POLICY, strip_comments=True)


# =============================================================================
# MAIN
# =============================================================================

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", type=str,
                        default="rego_policies/microwl.rego",
                        help="Output path for the generated Rego policy.")
    args = parser.parse_args()

    out = Path(args.output)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(REGO_POLICY)
    print(f"[OK] Rego policy written to {out.resolve()}")

    swrl_loc = compute_swrl_loc()
    rego_loc = compute_rego_loc()
    reduction = (1 - swrl_loc / rego_loc) * 100 if rego_loc else 0.0

    print("\n==== Authoring-effort comparison ====")
    print(f"SWRL rules (6 rules) : {swrl_loc} effective lines")
    print(f"Rego policy          : {rego_loc} effective lines")
    print(f"Reduction            : {reduction:.1f}% fewer lines in SWRL")
    print("=====================================")


if __name__ == "__main__":
    main()
